// PdfFooter.jsx
// The footer both printed documents repeat on every page. `fixed` repeats it; `render` gets per-page state. The disclaimer is not
// decoration: these documents must never be mistaken for an official academic record.

import { View, Text } from '@react-pdf/renderer'
import { shared as styles, EM_DASH } from './pdfStyles'

export default function PdfFooter() {
  return (
    <View style={styles.footer} fixed>
      <Text style={styles.footerText}>
        Generated by MyDegreePlan. Unofficial planning document {EM_DASH} not an academic record.
      </Text>
      <Text
        style={styles.footerText}
        render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`}
      />
    </View>
  )
}
